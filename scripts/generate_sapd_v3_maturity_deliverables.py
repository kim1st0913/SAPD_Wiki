def normalize_candidate_criterion(
    row: dict[str, Any],
    candidate: dict[str, Any],
    level: str,
    dim: str,
    text: str,
) -> str:
    context = specialized_context(row, candidate)
    if context:
        return context_criterion(row, candidate, level, dim, context)

    if level == "L1":
        if dim == "organization":
            text = re.sub(
                r"相关工作通常由",
                "相关工作可能尚未持续开展；已发生的活动通常由",
                text,
                count=1,
            )
        elif dim == "process":
            text = re.sub(
                r"^主要依据个人经验",
                "可能尚未形成可复核实践；已发生的活动主要依据个人经验",
                text,
                count=1,
            )
        elif dim == "tool":
            text = re.sub(
                r"^仅使用",
                "支撑机制可能缺失；已发生的活动仅使用",
                text,
                count=1,
            )
    if level == "L4":
        if dim == "organization":
            text = text.replace("量化目标责任、指标所有者", "运行结果责任、观察证据责任")
            text = re.sub(
                r"管理者定期依据.+?等经批准指标评审(.+?)的控制状态，"
                r"对超出阈值或风险容忍度的偏差",
                r"管理者按规定节奏结合持续监测、抽样检查、测试验证、审计复核、服务表现或适用的经批准衡量结果评审\1的控制状态，对偏离批准的控制目标、验收准则、可接受边界或风险容忍度的偏差",
                text,
            )
        elif dim == "process":
            metric_match = re.search(
                r"建立可重复的量化控制机制，明确(.+?)等指标的定义、数据源、统计周期、基线、目标值、警戒值和升级值；",
                text,
            )
            if metric_match:
                metrics = metric_match.group(1)
                text = re.sub(
                    r"建立可重复的量化控制机制，明确.+?等指标的定义、数据源、统计周期、基线、目标值、警戒值和升级值；",
                    "建立可重复的运行控制与复核机制，明确控制目标、适用边界、观察或测试方法、偏差识别和验收准则；",
                    text,
                    count=1,
                )
                text += (
                    f" 可在风险与数据可得性适合时，从{metrics}等候选衡量项中选择并批准口径；"
                    "不要求全部采用，也不把固定阈值作为通用门槛。"
                )
        elif dim == "tool":
            text = text.replace(
                "支持指标计算、阈值告警、趋势分析、抽样测试和纠偏复测",
                "支持持续观察、抽样测试、审计追溯、异常定位和纠偏复测",
            )
        elif dim == "data":
            text = re.sub(
                r"至少覆盖(.+?)，并能追溯",
                r"可按风险和数据可得性选用\1等衡量项辅助判断，并能追溯",
                text,
            )
            text += " 候选衡量项不是本级硬门槛；无法验证分母、方向或数据质量时，不得用该指标证明达标。"
    if level == "L5":
        text = text.replace("量化表现、根因", "运行表现、控制反馈、根因")
        text = text.replace("量化结果和根因", "运行证据、控制反馈和根因")
        text = text.replace("基于 Level 4 的趋势、阈值偏差、事件和复盘", "基于 Level 4 的运行证据、控制反馈、事件和复盘")
        text = text.replace("基于 Level4 的趋势、阈值偏差、事件和复盘", "基于 Level 4 的运行证据、控制反馈、事件和复盘")
        text = text.replace("指标趋势、事件、复发问题", "运行记录、问题趋势、事件和复发问题")
        text = text.replace(
            "AI、机器学习或大模型可作为可选手段，但不是 Level 5 的必要条件。",
            "",
        ).strip()
        text = re.sub(
            r"[；。]?AI、机器学习或大模型[^。]*。?",
            "",
            text,
        ).strip()
    if dim == "tool" and row["focusCode"].startswith(("G-", "M-")):
        text = (
            "可由受控模板、台账、工作流、共享存储或专业平台按需支持；"
            "是否采用专用平台不单独决定成熟度。"
            + text
        )
    return re.sub(r"\s{2,}", " ", text).strip()


def consulting_source_refs(row: dict[str, Any]) -> list[str]:
    refs = ["SRC-SAPD-CURRENT", "SRC-CHAT-V3-DRAFTS", "SRC-SCF-2026"]
    code = row["focusCode"]
    if code.startswith("T-"):
        refs.extend(["SRC-NIST-80053", "SRC-NIST-CSF", "SRC-CIS", "SRC-GBT-22239"])
    if code.startswith(("T-AS.DG", "T-PD.DP", "M-SA.RE-03")):
        refs.extend(["SRC-DSP", "SRC-ISO-27001"])
    if code.startswith(("T-AD", "T-IN", "T-OF")):
        refs.extend(["SRC-C2M2", "SRC-SLIDING-SCALE"])
    if code.startswith(("G-", "M-")):
        refs.extend(["SRC-NIST-CSF", "SRC-ISO-27001", "SRC-EA-SABSA"])
    if code.startswith("T-OF"):
        refs.append("SRC-CRF")
    return list(dict.fromkeys(refs))


