def parse_range_rows(candidates: dict[str, Any]) -> dict[str, dict[str, str]]:
    result: dict[str, dict[str, str]] = {}
    for code, focus in candidates["focuses"].items():
        item = {
            "levelStart": focus["levelStart"],
            "levelEnd": focus["levelEnd"],
            "applicability": focus["applicability"],
            "rangeRationale": focus["rangeRationale"],
            "capabilityObjective": focus.get("capabilityObjective", ""),
            "bestPracticeReferences": focus.get("bestPracticeReferences", ""),
            "candidateSourceFile": focus["sourceFile"],
            "candidateSourceLine": focus["sourceLine"],
        }
        if code in RANGE_REVIEW_OVERRIDES:
            item.update(RANGE_REVIEW_OVERRIDES[code])
        if code in RANGE_RATIONALE_REWRITES:
            item["rangeRationale"] = RANGE_RATIONALE_REWRITES[code]
        result[code] = item
    return result


