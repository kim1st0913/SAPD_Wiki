def compact_terms(value: str, max_items: int = 4, max_chars: int = 48) -> str:
    text = re.sub(r"\s+", "", value or "").strip("；。，“”")
    if not text:
        return ""
    items = [item.strip("；。，“”") for item in re.split(r"[、，；]", text) if item.strip("；。，“”")]
    selected: list[str] = []
    for item in items:
        candidate = "、".join(selected + [item])
        if selected and (len(selected) >= max_items or len(candidate) > max_chars):
            break
        selected.append(item)
    result = "、".join(selected) if selected else text[:max_chars]
    if len(items) > len(selected) and not result.endswith("等"):
        result += "等"
    return result


def extract_candidate_phrase(
    text: str,
    patterns: list[str],
    fallback: str,
    *,
    max_items: int = 4,
    max_chars: int = 48,
) -> str:
    for pattern in patterns:
        match = re.search(pattern, text or "")
        if match and match.group(1).strip():
            return compact_terms(match.group(1), max_items=max_items, max_chars=max_chars)
    first_clause = re.split(r"[；。]", text or "", maxsplit=1)[0]
    return compact_terms(first_clause or fallback, max_items=max_items, max_chars=max_chars)


