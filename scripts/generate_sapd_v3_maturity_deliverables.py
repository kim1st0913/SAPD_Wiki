def specialized_context(row: dict[str, Any], candidate: dict[str, Any]) -> dict[str, str]:
    if row["assessmentCode"] in TECHNICAL_ASSESSMENT_CONTEXTS:
        return TECHNICAL_ASSESSMENT_CONTEXTS[row["assessmentCode"]]
    focus_context = consulting_focus_contexts().get(row["focusCode"])
    if focus_context:
        context = dict(focus_context)
        if row["focusCode"] in {
            "T-AS.AD-02",
            "T-AS.CM-02",
            "T-AS.LA-01",
            "T-AS.LA-02",
            "T-PD.AC-02",
            "T-PD.DP-05",
            "T-PD.DP-06",
            "T-AD.IR-06",
            "T-AD.SV-01",
        }:
            object_focus = candidate.get("objectFocus")
            if object_focus:
                context["object"] = f"{object_focus}范围内的{context['object']}"
        return context
    return derived_candidate_context(row, candidate)


